//! Instalação RESPEITOSA do medidor de janela de uso via statusline (dialeto
//! `UsageWindowSource::ClaudeStatusline`) — SEMPRE por gesto do usuário
//! (botão em Configurações), nunca no boot.
//!
//! As regras do padrão respeitoso (hooks-plan §4 + estudo do Xirp):
//!   1. ENCADEAR, nunca substituir: o comando de statusline vigente (nesta
//!      máquina, o wrapper do Xirp — que por sua vez preserva o do Troco) é
//!      preservado no header do script gerado e re-executado com o MESMO
//!      stdin; o stdout dele continua sendo a statusline do usuário.
//!   2. Script gerado com header "não edite" em diretório NOSSO
//!      (app_data_dir/statusline/); o settings.json só referencia o PATH
//!      estável — o token/porta rotacionam no hook-endpoint.json que o script
//!      lê a cada tick.
//!   3. Backup antes de mexer (`settings.json.bak-mycockpit-<ts>`), JSON por
//!      parse→merge→write atômico, nunca regex.
//!   4. Desinstalação limpa: restaura o VALOR do comando anterior (ou remove
//!      o statusLine se não havia) e apaga o script. Honestidade do claim: a
//!      re-serialização pode mudar formatação e ordem de chaves do arquivo —
//!      `preserve_order` do serde_json foi avaliado e REJEITADO de propósito
//!      (é feature global: mudaria a ordem de todo Map do app e invalidaria
//!      os fingerprints já persistidos do mcp_control, que hasheiam JSON
//!      serializado). O que é garantido é o CONTEÚDO, não os bytes.
//!   4b. Fail-closed onde o efeito é destrutivo: se o slot aponta pro nosso
//!      script mas o script sumiu/perdeu o header (limpador de caches, reset),
//!      instalar/desinstalar ABORTA com erro apontando o backup mais recente —
//!      seguir adiante perderia em silêncio a statusline encadeada (o wrapper
//!      do Xirp, nesta máquina).
//!   5. Fail-open do lado do script: curl com timeout de 1s em background,
//!      erro engolido, `exit 0` sempre — a statusline do usuário NUNCA quebra
//!      nem atrasa porque o app morreu.
//!   6. Só posta o tick que TRAZ `rate_limits` (guarda de substring em shell
//!      puro, padrão do Orca): a statusline tica várias vezes por segundo
//!      durante streaming, mas o rate_limits muda 1x por turno — sem a guarda
//!      o custo do spawn do curl era pago em todo tick. A statusline original
//!      encadeada roda SEMPRE, fora da guarda (ela não pode sumir quando o
//!      payload não tem rate_limits).

use crate::adapters::{capabilities_of, UsageWindowSource};
use serde::Serialize;
use serde_json::{json, Value};
use std::path::PathBuf;
use tauri::{AppHandle, Manager};

const SCRIPT_NAME: &str = "mycockpit-statusline.sh";
const ORIGINAL_MARKER: &str = "# mycockpit-original-command:";

/// Estado da instalação por agent — o que a UI de Configurações mostra,
/// incluindo o PREVIEW exato do que será escrito (transparência antes do
/// gesto) e o comando que será encadeado.
#[derive(Serialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct StatuslineStatus {
    /// O slot de statusline aponta pro nosso script?
    pub installed: bool,
    pub settings_path: String,
    pub script_path: String,
    /// O que ocupa o slot HOJE (instalado ou não).
    pub current_command: Option<String>,
    /// O que o nosso script encadeia (só quando instalado).
    pub chained_command: Option<String>,
    /// JSON exato do objeto `statusLine` que a instalação escreverá.
    pub preview: String,
    /// Estado inconsistente detectado (ex.: slot aponta pro nosso script mas
    /// ele sumiu do disco) — a UI mostra; instalar/desinstalar aborta com o
    /// mesmo motivo.
    pub warning: Option<String>,
}

