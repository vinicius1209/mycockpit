#[tauri::command]
pub fn usage_statusline_status(app: AppHandle, agent: String) -> Result<StatuslineStatus, String> {
    status_of(&app, &agent)
}

/// Instala (ou reinstala, idempotente): gera o script encadeador e aponta o
/// slot pra ele, com backup e preservação do comando anterior.
#[tauri::command]
pub fn usage_statusline_install(app: AppHandle, agent: String) -> Result<StatuslineStatus, String> {
    require_statusline(&agent)?;
    let spath = settings_path()?;
    let script = script_path(&app)?;
    let script_str = script.to_string_lossy().to_string();
    let settings = read_settings(&spath)?;
    let existing_script = std::fs::read_to_string(&script).ok();
    // Fail-closed: slot nosso sem script legível aborta ANTES de escrever
    // qualquer coisa — reinstalar por cima geraria um script SEM o chain e a
    // statusline do usuário (Xirp/Troco) sumiria em silêncio.
    let original = resolve_original(
        current_command(&settings),
        &script_str,
        existing_script.as_deref(),
    )
    .map_err(|e| with_backup_hint(e, &spath))?;
    let endpoint = crate::hook_gateway::endpoint_file(&app)?;
    write_script(
        &script,
        &render_script(&agent, original.as_deref(), &endpoint.to_string_lossy()),
    )?;
    backup_settings(&spath)?;
    write_settings(&spath, &with_script(&settings, &script_str))?;
    log::info!("statusline: medidor instalado pra {agent} (encadeando {original:?})");
    status_of(&app, &agent)
}

/// Desinstala limpo: restaura o comando anterior (ou remove o statusLine se
/// não havia) e apaga o script. O backup da instalação fica no disco.
#[tauri::command]
pub fn usage_statusline_uninstall(
    app: AppHandle,
    agent: String,
) -> Result<StatuslineStatus, String> {
    require_statusline(&agent)?;
    let spath = settings_path()?;
    let script = script_path(&app)?;
    let script_str = script.to_string_lossy().to_string();
    let settings = read_settings(&spath)?;
    // só mexe no slot se ele ainda é NOSSO — o usuário pode ter trocado a
    // statusline depois; aí restaurar o "original" antigo seria regressão.
    if current_command(&settings).as_deref() == Some(script_str.as_str()) {
        // Fail-closed: script sumido/sem header = não dá pra saber o que
        // restaurar; remover o statusLine inteiro apagaria a statusline
        // encadeada (Xirp) em silêncio. Aborta apontando o backup.
        let content = std::fs::read_to_string(&script).ok();
        let original =
            resolve_original(Some(script_str.clone()), &script_str, content.as_deref())
                .map_err(|e| with_backup_hint(e, &spath))?;
        backup_settings(&spath)?;
        write_settings(&spath, &without_script(&settings, original.as_deref()))?;
    }
    if script.exists() {
        std::fs::remove_file(&script).map_err(|e| e.to_string())?;
    }
    log::info!("statusline: medidor desinstalado pra {agent}");
    status_of(&app, &agent)
}

