/// Renderiza o script encadeador. `original` = o comando que ocupava o slot
/// (preservado no header E re-executado no fim, padrão do wrapper do Xirp).
pub fn render_script(engine: &str, original: Option<&str>, endpoint_file: &str) -> String {
    let chain = match original {
        Some(cmd) if !cmd.trim().is_empty() => format!(
            "# encadeia a statusline que ocupava o slot (o stdout dela é a sua statusline):\nprintf '%s' \"$input\" | {cmd}\n"
        ),
        _ => "# não havia statusline antes: não imprime nada (o Claude mostra o padrão dele).\n".to_string(),
    };
    format!(
        "#!/bin/bash\n\
         # Generated by MyCockpit — DO NOT EDIT (regenerado a cada instalação)\n\
         # mycockpit-schema: 1\n\
         {ORIGINAL_MARKER} {original}\n\
         # Medidor de janela de uso: envia o stdin da statusline (rate_limits)\n\
         # pro MyCockpit em loopback e repassa pra statusline original acima.\n\
         # Fail-open: app fechado = curl falha em <1s em background e NADA muda\n\
         # na sua statusline. Desinstalação limpa em Configurações do MyCockpit.\n\
         input=$(cat)\n\
         # Só o tick que traz rate_limits interessa (muda 1x por turno); os demais\n\
         # ticks (vários por segundo durante streaming) nem spawnam o curl.\n\
         case \"$input\" in *'\"rate_limits\"'*)\n\
         \x20 ep=\"{endpoint_file}\"\n\
         \x20 if [ -r \"$ep\" ]; then\n\
         \x20   port=$(sed -n 's/.*\"port\":[[:space:]]*\\([0-9]*\\).*/\\1/p' \"$ep\" | head -1)\n\
         \x20   token=$(sed -n 's/.*\"token\":[[:space:]]*\"\\([a-f0-9]*\\)\".*/\\1/p' \"$ep\" | head -1)\n\
         \x20   if [ -n \"$port\" ] && [ -n \"$token\" ]; then\n\
         \x20     printf '%s' \"$input\" | curl -s -X POST \"http://127.0.0.1:${{port}}/hook/{engine}\" \\\n\
         \x20       -H \"Authorization: Bearer ${{token}}\" -H \"Content-Type: application/json\" \\\n\
         \x20       --connect-timeout 1 --max-time 1 --data-binary @- >/dev/null 2>&1 &\n\
         \x20   fi\n\
         \x20 fi\n\
         ;; esac\n\
         {chain}\
         exit 0\n",
        original = original.unwrap_or(""),
    )
}

/// Extrai o comando original do header de um script NOSSO. Vazio/ausente →
/// None (não havia statusline antes da instalação).
pub fn original_from_script(content: &str) -> Option<String> {
    for line in content.lines() {
        if let Some(rest) = line.strip_prefix(ORIGINAL_MARKER) {
            let cmd = rest.trim();
            return (!cmd.is_empty()).then(|| cmd.to_string());
        }
    }
    None
}

/// Comando no slot de statusline do settings (só `type: "command"` tem um).
pub fn current_command(settings: &Value) -> Option<String> {
    let sl = settings.get("statusLine")?;
    sl.get("command")?.as_str().map(str::to_string)
}

/// Settings com o slot apontando pro NOSSO script: preserva todos os outros
/// campos do arquivo E do objeto statusLine (padding etc.), só troca
/// type/command. Nunca regex: parse→merge.
pub fn with_script(settings: &Value, script_path: &str) -> Value {
    let mut out = settings.clone();
    if !out.is_object() {
        out = json!({});
    }
    let mut sl = out
        .get("statusLine")
        .filter(|v| v.is_object())
        .cloned()
        .unwrap_or_else(|| json!({}));
    sl["type"] = json!("command");
    sl["command"] = json!(script_path);
    out["statusLine"] = sl;
    out
}

/// Settings restaurado na desinstalação: `original` volta pro slot; sem
/// original, o objeto statusLine sai inteiro (era ausente antes de nós).
pub fn without_script(settings: &Value, original: Option<&str>) -> Value {
    let mut out = settings.clone();
    match original {
        Some(cmd) => {
            let mut sl = out
                .get("statusLine")
                .filter(|v| v.is_object())
                .cloned()
                .unwrap_or_else(|| json!({}));
            sl["type"] = json!("command");
            sl["command"] = json!(cmd);
            out["statusLine"] = sl;
        }
        None => {
            if let Some(obj) = out.as_object_mut() {
                obj.remove("statusLine");
            }
        }
    }
    out
}

